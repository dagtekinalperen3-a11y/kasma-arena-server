-- Hesaplar. Oyunda "kullanıcı adı" olarak görünen ad burada.
create table if not exists oyuncular (
    id                bigint generated by default as identity primary key,
    kullanici_adi     text unique,                 -- sıralamada görünen ad
    eposta            text,                        -- kurtarma / Google e-postası
    giris_yontemi     text not null default 'password',   -- password | google
    sifre_ozeti       text,                        -- scrypt özeti (şifrenin kendisi değil)
    google_kimligi    text,
    google_adi        text,                        -- Google hesabındaki ad (bilgi)
    kayit_tarihi      timestamptz not null default now(),
    son_giris         timestamptz,                 -- oyunu en son açtığı an
    son_gorulme       timestamptz,                 -- oyun açıkken dakikada bir tazelenir
    son_cikis         timestamptz,                 -- oyunu en son kapattığı an
    toplam_oynama_sn  bigint  not null default 0,  -- toplam oynama (saniye)
    toplam_oynama     text generated always as (
                          (toplam_oynama_sn / 3600)::text || ' sa '
                          || lpad(((toplam_oynama_sn % 3600) / 60)::text, 2, '0') || ' dk'
                      ) stored,
    oturum_sayisi     integer not null default 0,  -- oyunu kaç kez açtı
    surum             text,                        -- en son kullandığı oyun sürümü
    platform          text                         -- pc | mobile
);
create index if not exists oyuncular_ad_kucuk     on oyuncular (lower(kullanici_adi));
create index if not exists oyuncular_eposta_kucuk on oyuncular (lower(eposta));

-- Giriş jetonları (jetonun kendisi değil, SHA-256 özeti tutulur).
create table if not exists oturumlar (
    token_ozeti   text primary key,
    oyuncu_id     bigint not null references oyuncular(id) on delete cascade,
    cihaz_ozeti   text,
    olusturma     timestamptz not null default now(),
    bitis         timestamptz not null
);
create index if not exists oturumlar_oyuncu on oturumlar (oyuncu_id);

-- Hesabın kalıcı ilerlemesi: elmas, skinler, petler, ustalık, istatistik.
-- Sık bakılan sayılar ayrı sütunda, gerisi "veri" içinde (JSON).
create table if not exists ilerleme (
    oyuncu_id        bigint primary key references oyuncular(id) on delete cascade,
    elmas            bigint  not null default 0,
    kazanilan_elmas  bigint  not null default 0,
    harcanan_elmas   bigint  not null default 0,
    en_iyi_skor      bigint  not null default 0,
    en_iyi_dalga     integer not null default 0,
    toplam_oldurme   bigint  not null default 0,
    kosu_sayisi      integer not null default 0,
    skin_sayisi      integer not null default 0,
    pet_sayisi       integer not null default 0,
    veri             jsonb   not null default '{}'::jsonb,
    guncelleme       timestamptz not null default now()
);

-- Her bitmiş koşu (giriş yapmış oyuncunun). dunya_siralamasi = true olanlar
-- dünya sıralamasına girer (Taş Meydan haritası); öbürleri yalnızca geçmiş.
create table if not exists skorlar (
    id                bigint generated by default as identity primary key,
    oyuncu_id         bigint references oyuncular(id) on delete set null,
    kullanici_adi     text    not null,
    skor              bigint  not null default 0,
    oldurme           bigint  not null default 0,
    dalga             integer not null default 0,
    sure_sn           double precision not null default 0,
    sure              text generated always as (
                          case when floor(sure_sn) >= 3600
                               then (floor(sure_sn)::bigint / 3600)::text || ':' else '' end
                          || lpad(((floor(sure_sn)::bigint % 3600) / 60)::text, 2, '0') || ':'
                          || lpad((floor(sure_sn)::bigint % 60)::text, 2, '0')
                      ) stored,
    zorluk            text    not null default 'normal',   -- normal | hard | nightmare
    harita            text    not null default 'stone',
    platform          text    not null default 'pc',       -- pc | mobile
    dunya_siralamasi  boolean not null default true,
    skin              text    default 'default',
    kosu_karti        jsonb,                               -- silahlar, kitaplar, hasar
    tarih             timestamptz not null default now(),
    imza              text                                 -- aynı gönderi iki kez yazılmasın
);
create unique index if not exists skorlar_imza on skorlar (imza) where imza is not null;
create index if not exists skorlar_dunya  on skorlar (platform, dunya_siralamasi, skor desc);
create index if not exists skorlar_oyuncu on skorlar (oyuncu_id, skor desc);

-- Oyunu her açışı bir satır: ne zaman girdi, ne zaman çıktı, ne kadar kaldı.
create table if not exists oyun_oturumlari (
    id          bigint generated by default as identity primary key,
    oyuncu_id   bigint not null references oyuncular(id) on delete cascade,
    giris       timestamptz not null default now(),
    cikis       timestamptz not null default now(),
    sure_sn     integer not null default 0,
    sure        text generated always as (
                    (sure_sn / 3600)::text || ' sa '
                    || lpad(((sure_sn % 3600) / 60)::text, 2, '0') || ' dk'
                ) stored,
    acik        boolean not null default true,   -- true: oyun hâlâ açık
    surum       text,
    platform    text
);
create index if not exists oyun_oturumlari_oyuncu on oyun_oturumlari (oyuncu_id, id desc);

-- Arkadaşlık: isteyen -> istenen. durum: pending (bekliyor) | accepted (arkadaş)
create table if not exists arkadaslar (
    id          bigint generated by default as identity primary key,
    isteyen_id  bigint not null references oyuncular(id) on delete cascade,
    istenen_id  bigint not null references oyuncular(id) on delete cascade,
    durum       text   not null default 'pending',
    tarih       timestamptz not null default now()
);
create index if not exists arkadaslar_isteyen on arkadaslar (isteyen_id);
create index if not exists arkadaslar_istenen on arkadaslar (istenen_id);

-- Arkadaş mesajları. tur: text (mesaj) | invite (2 kişilik davet, metin = oda kodu)
create table if not exists mesajlar (
    id           bigint generated by default as identity primary key,
    gonderen_id  bigint not null references oyuncular(id) on delete cascade,
    alici_id     bigint not null references oyuncular(id) on delete cascade,
    tur          text   not null default 'text',
    metin        text   not null default '',
    tarih        timestamptz not null default now(),
    okunma       timestamptz                       -- boş: okunmadı
);
create index if not exists mesajlar_alici    on mesajlar (alici_id, okunma);
create index if not exists mesajlar_konusma  on mesajlar (gonderen_id, alici_id, id desc);

-- 2 kişilik dünya sıralaması
create table if not exists ikili_skorlar (
