-- epoch (saniye) -> tarih. 0 / boş -> NULL
create or replace function _eski_tarih(v double precision) returns timestamptz
language sql immutable as $$
    select case when v is null or v <= 0 then null else to_timestamp(v) end
$$;

do $$ begin
    insert into oyuncular (id, kullanici_adi, eposta, giris_yontemi, sifre_ozeti,
                           google_kimligi, google_adi, kayit_tarihi)
    overriding system value
    select a.id, nullif(a.username, ''), nullif(a.email, ''),
           coalesce(nullif(a.provider, ''), 'password'), a.password_hash,
           a.google_sub, a.name,
           coalesce(_eski_tarih(a.created_at::double precision), now())
    from accounts a
    on conflict do nothing;
    raise notice 'oyuncular: tamam';
exception when others then raise notice 'accounts atlandı: %', sqlerrm;
end $$;

do $$ begin
    insert into oturumlar (token_ozeti, oyuncu_id, cihaz_ozeti, olusturma, bitis)
    select s.token_hash, s.account_id::bigint, s.device_hash,
           coalesce(_eski_tarih(s.created_at::double precision), now()),
           _eski_tarih(s.expires_at::double precision)
    from sessions s
    where exists (select 1 from oyuncular o where o.id = s.account_id::bigint)
      and s.expires_at::double precision > extract(epoch from now())
    on conflict do nothing;
    raise notice 'oturumlar: tamam';
exception when others then raise notice 'sessions atlandı: %', sqlerrm;
end $$;

do $$ begin
    insert into ilerleme (oyuncu_id, elmas, kazanilan_elmas, harcanan_elmas, en_iyi_skor,
                          en_iyi_dalga, toplam_oldurme, kosu_sayisi, skin_sayisi, pet_sayisi,
                          veri, guncelleme)
    select p.account_id::bigint,
           coalesce(p.gems, 0), coalesce(p.gems_earned, 0), coalesce(p.gems_spent, 0),
           coalesce(p.best_score, 0)::bigint, coalesce(p.best_wave, 0)::integer,
           coalesce(p.total_kills, 0)::bigint, coalesce(p.runs, 0)::integer,
           coalesce(p.skin_count, 0)::integer, coalesce(p.pet_count, 0)::integer,
           -- dünya sıralaması yasakları kaldırıldı: eski yasak bayrakları taşınmaz
           (coalesce(p.data::text, '{}')::jsonb - 'board_banned' - 'ban_reasons'),
           coalesce(_eski_tarih(p.updated_at::double precision), now())
    from player_data p
    where exists (select 1 from oyuncular o where o.id = p.account_id::bigint)
    on conflict do nothing;
    raise notice 'ilerleme: tamam';
exception when others then raise notice 'player_data atlandı: %', sqlerrm;
end $$;

