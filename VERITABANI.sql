create or replace function tr_saat(t timestamptz) returns text
language sql stable as $$
    select case when t is null then '-'
                else to_char(t at time zone 'Europe/Istanbul', 'DD.MM.YYYY HH24:MI') end
$$;

-- "3 dk önce", "5 sa önce", "2 gün önce"
create or replace function ne_zaman(t timestamptz) returns text
language sql stable as $$
    select case
        when t is null then '-'
        when now() - t < interval '1 minute' then 'az önce'
        when now() - t < interval '1 hour'
            then extract(minute from now() - t)::int::text || ' dk önce'
        when now() - t < interval '1 day'
            then floor(extract(epoch from now() - t) / 3600)::int::text || ' sa önce'
        else floor(extract(epoch from now() - t) / 86400)::int::text || ' gün önce'
    end
$$;

-- Oyuncu şu an oyunda mı? (son 3 dakikada haber verdi ve çıkış yapmadı)
create or replace function oyunda_mi(gorulme timestamptz, cikis timestamptz) returns boolean
language sql stable as $$
    select gorulme is not null and gorulme > now() - interval '3 minutes'
           and (cikis is null or cikis < gorulme)
$$;

-- Her oyuncu tek satır: kim, ne zaman, ne kadar, ne durumda.
drop view if exists oyuncu_ozeti;
create view oyuncu_ozeti with (security_invoker = true) as
select
    o.id                                                   as "No",
    coalesce(o.kullanici_adi, '(ad seçmedi)')              as "Oyuncu",
    case when oyunda_mi(o.son_gorulme, o.son_cikis)
         then 'ÇEVRİMİÇİ' else 'çevrimdışı' end            as "Durum",
    o.toplam_oynama                                        as "Toplam oynama",
    o.oturum_sayisi                                        as "Kaç kez girdi",
    tr_saat(o.son_giris)                                   as "Son giriş",
    case when oyunda_mi(o.son_gorulme, o.son_cikis) then 'oyunda'
         else tr_saat(greatest(o.son_cikis, o.son_gorulme)) end as "Son çıkış",
    ne_zaman(greatest(o.son_cikis, o.son_gorulme))         as "En son görülme",
    coalesce(p.elmas, 0)                                   as "Elmas",
    coalesce(p.en_iyi_skor, 0)                             as "En iyi skor",
    coalesce(p.en_iyi_dalga, 0)                            as "En iyi dalga",
    coalesce(p.kosu_sayisi, 0)                             as "Koşu sayısı",
    coalesce(p.toplam_oldurme, 0)                          as "Toplam öldürme",
    (select count(*) from skorlar s where s.oyuncu_id = o.id)          as "Kayıtlı skor",
    (select min(r.sira) from (
        select s2.oyuncu_id, row_number() over (order by s2.skor desc) as sira
        from skorlar s2 where s2.dunya_siralamasi and s2.platform = 'pc') r
     where r.oyuncu_id = o.id)                             as "Dünya sırası",
    coalesce(o.eposta, '-')                                as "E-posta",
    o.giris_yontemi                                        as "Giriş türü",
    tr_saat(o.kayit_tarihi)                                as "Kayıt tarihi",
    coalesce(o.surum, '-')                                 as "Sürüm"
from oyuncular o
left join ilerleme p on p.oyuncu_id = o.id
order by o.son_gorulme desc nulls last, o.id;

-- Dünya sıralaması (bilgisayar), ilk 100 koşu
drop view if exists dunya_ilk_100;
create view dunya_ilk_100 with (security_invoker = true) as
select
    row_number() over (order by s.skor desc, s.tarih)      as "Sıra",
    s.kullanici_adi                                        as "Oyuncu",
    s.skor                                                 as "Skor",
    s.dalga                                                as "Dalga",
    s.oldurme                                              as "Öldürme",
    s.sure                                                 as "Süre",
    s.zorluk                                               as "Zorluk",
    s.skin                                                 as "Skin",
    tr_saat(s.tarih)                                       as "Tarih",
    s.id                                                   as "Skor no"
from skorlar s
where s.dunya_siralamasi and s.platform = 'pc'
order by s.skor desc, s.tarih
limit 100;

-- Herkesin bütün skorları: oyuncuya göre gruplu, her oyuncuda en iyiden kötüye
drop view if exists oyuncu_skorlari;
create view oyuncu_skorlari with (security_invoker = true) as
select
    s.kullanici_adi                                        as "Oyuncu",
    row_number() over (partition by s.kullanici_adi order by s.skor desc) as "Oyuncunun kaçıncı skoru",
    s.skor                                                 as "Skor",
    s.dalga                                                as "Dalga",
    s.oldurme                                              as "Öldürme",
    s.sure                                                 as "Süre",
    s.zorluk                                               as "Zorluk",
    s.harita                                               as "Harita",
    case when s.dunya_siralamasi then 'evet' else 'hayır' end as "Dünya sıralamasında",
    s.platform                                             as "Platform",
    tr_saat(s.tarih)                                       as "Tarih",
    s.id                                                   as "Skor no"
from skorlar s
order by lower(s.kullanici_adi), s.skor desc;

-- Kim ne zaman girdi, ne zaman çıktı
drop view if exists giris_cikis_gecmisi;
create view giris_cikis_gecmisi with (security_invoker = true) as
select
    o.kullanici_adi                                        as "Oyuncu",
    tr_saat(g.giris)                                       as "Giriş",
    case when g.acik and g.cikis > now() - interval '3 minutes' then 'oyunda'
         else tr_saat(g.cikis) end                         as "Çıkış",
    g.sure                                                 as "Süre",
    coalesce(g.surum, '-')                                 as "Sürüm",
    coalesce(g.platform, '-')                              as "Platform",
    g.id                                                   as "No"
from oyun_oturumlari g
join oyuncular o on o.id = g.oyuncu_id
order by g.giris desc;

drop view if exists mesaj_gecmisi;
create view mesaj_gecmisi with (security_invoker = true) as
select
    tr_saat(m.tarih)                                       as "Tarih",
    g.kullanici_adi                                        as "Gönderen",
    a.kullanici_adi                                        as "Alıcı",
    case when m.tur = 'invite' then '(2 kişilik davet: ' || m.metin || ')'
         else m.metin end                                  as "Mesaj",
    case when m.okunma is null then 'okunmadı' else 'okundu' end as "Durum",
    m.id                                                   as "No"
from mesajlar m
join oyuncular g on g.id = m.gonderen_id
join oyuncular a on a.id = m.alici_id
order by m.id desc;

drop view if exists arkadaslik_listesi;
create view arkadaslik_listesi with (security_invoker = true) as
select
    i.kullanici_adi                                        as "İsteyen",
    e.kullanici_adi                                        as "İstenen",
    case when f.durum = 'accepted' then 'arkadaş' else 'istek bekliyor' end as "Durum",
    tr_saat(f.tarih)                                       as "Tarih"
from arkadaslar f
join oyuncular i on i.id = f.isteyen_id
join oyuncular e on e.id = f.istenen_id
order by f.tarih desc;

drop view if exists elmas_hareketleri;
create view elmas_hareketleri with (security_invoker = true) as
select
    tr_saat(g.zaman)                                       as "Zaman",
    o.kullanici_adi                                        as "Oyuncu",
    g.tur                                                  as "Tür",
    g.degisim                                              as "Değişim",
    g.toplam                                               as "Sonra",
    g.aciklama                                             as "Açıklama"
from olay_gunlugu g
left join oyuncular o on o.id = g.oyuncu_id
order by g.id desc;

drop view if exists ikili_siralama;
create view ikili_siralama with (security_invoker = true) as
select
    row_number() over (order by c.skor desc)               as "Sıra",
    c.oyuncu_a || ' + ' || c.oyuncu_b                      as "İkili",
    c.skor                                                 as "Skor",
    c.dalga                                                as "Dalga",
    c.oldurme                                              as "Öldürme",
    c.sure                                                 as "Süre",
    c.zorluk                                               as "Zorluk",
    tr_saat(c.tarih)                                       as "Tarih"
from ikili_skorlar c
order by c.skor desc
limit 100;

-- Görünümler yalnızca panelden (ve service_role'den) okunsun
revoke all on oyuncu_ozeti, dunya_ilk_100, oyuncu_skorlari, giris_cikis_gecmisi,
              mesaj_gecmisi, arkadaslik_listesi, elmas_hareketleri, ikili_siralama
    from anon, authenticated;

