               coalesce(d.name, 'İsimsiz'),
               coalesce(d.score::numeric, 0)::bigint, coalesce(d.kills::numeric, 0)::bigint,
               coalesce(d.wave::numeric, 0)::integer, coalesce(d.run_time::double precision, 0),
